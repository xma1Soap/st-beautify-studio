// Writes the 变量结构 script: a zod description of stat_data registered with MVU (the new, zod-based MVU).
// Inside TavernHelper scripts `z` (zod 4) is a global, so the script only imports registerMvuSchema.
import * as z from 'zod';
import type { VarNode } from './types';
import { stageKey, varKey } from './vars';

// the simulator shows zod's messages to newcomers, so have them in Chinese
z.config(z.locales.zhCN());

export const MVU_BUNDLE_URL = 'https://testingcf.jsdelivr.net/gh/MagicalAstrogy/MagVarUpdate/artifact/bundle.js';
export const MVU_ZOD_URL = 'https://testingcf.jsdelivr.net/gh/StageDog/tavern_resource/dist/util/mvu_zod.js';

/** Object key as JS source: bare when it is a valid name (Chinese is fine), quoted otherwise. */
export const jsKey = (k: string) => (/^[\p{L}_$][\p{L}\p{N}_$]*$/u.test(k) ? k : JSON.stringify(k));

/** `obj.key`, or `obj["key"]` when the key is not a valid name */
const prop = (obj: string, k: string) => (jsKey(k) === k ? `${obj}.${k}` : `${obj}[${JSON.stringify(k)}]`);

/** String literal; JSON escaping is valid JS and leaves no way out of the string. */
const str = (s: string) => JSON.stringify(s);

const pad = (n: number) => '  '.repeat(n);

function numberSchema(v: VarNode): string {
  let body = 'v';
  if (v.integer) body = `Math.round(${body})`;
  if (v.min != null && v.max != null) body = `Math.min(Math.max(${body}, ${v.min}), ${v.max})`;
  else if (v.min != null) body = `Math.max(${body}, ${v.min})`;
  else if (v.max != null) body = `Math.min(${body}, ${v.max})`;
  return body === 'v' ? 'z.coerce.number()' : `z.coerce.number().transform(v => ${body})`;
}

/** `v < 20 ? 'A' : v < 40 ? 'B' : 'C'` for stages A from 0, B from 20, C from 40 */
function stageExpr(v: VarNode, value: string): string {
  const st = [...(v.stages ?? [])].sort((a, b) => a.from - b.from);
  let expr = str(st[st.length - 1].label);
  for (let i = st.length - 2; i >= 0; i--) expr = `${value} < ${st[i + 1].from} ? ${str(st[i].label)} : ${expr}`;
  return expr;
}

function objectSchema(children: VarNode[], depth: number, inTable: boolean): string {
  const lines = children.map((c) => `${pad(depth + 1)}${jsKey(varKey(c))}: ${schemaOf(c, depth + 1, inTable)},`);
  let out = `z.object({\n${lines.join('\n')}\n${pad(depth)}})`;
  const staged = children.filter((c) => c.kind === 'number' && c.stages?.length);
  if (staged.length) {
    const adds = staged.map((c) => `${pad(depth + 2)}${jsKey(stageKey(c))}: ${stageExpr(c, prop('data', varKey(c)))},`);
    out += `.transform(data => ({\n${pad(depth + 2)}...data,\n${adds.join('\n')}\n${pad(depth + 1)}}))`;
  }
  return out;
}

function schemaOf(v: VarNode, depth: number, inTable = false): string {
  let s: string;
  switch (v.kind) {
    case 'number':
      s = numberSchema(v);
      break;
    case 'text':
      s = 'z.string()';
      break;
    case 'bool':
      s = 'z.boolean()';
      break;
    case 'choice':
      s = `z.enum([${(v.options ?? []).map(str).join(', ')}])`;
      break;
    case 'list':
      s = 'z.array(z.string())';
      break;
    case 'group':
      s = objectSchema(v.children ?? [], depth, false);
      break;
    case 'table': {
      const row = objectSchema(v.children ?? [], depth + 1, true);
      s = `z.record(\n${pad(depth + 1)}z.string().describe(${str(v.rowName || '名字')}),\n${pad(depth + 1)}${row},\n${pad(depth)})`;
      const drop = v.dropRowWhenZero && (v.children ?? []).find((f) => f.name === v.dropRowWhenZero && f.kind === 'number');
      if (drop) {
        s += `.transform(rows => Object.fromEntries(Object.entries(rows).filter(([, row]) => ${prop('row', varKey(drop))} > 0)))`;
      }
      break;
    }
  }
  // a new table row may leave out fields that have a default
  if (inTable && v.init !== undefined && v.kind !== 'group' && v.kind !== 'table') s += `.prefault(${JSON.stringify(v.init)})`;
  return s;
}

/** The zod expression for the whole stat_data. */
export function schemaCode(vars: VarNode[]): string {
  return objectSchema(vars, 0, false);
}

/** The full 变量结构 script. */
export function schemaScript(vars: VarNode[]): string {
  return [
    `import { registerMvuSchema } from '${MVU_ZOD_URL}';`,
    '',
    '// 由酒馆美化工坊生成：变量的类型、范围和自动算出的阶段',
    `const Schema = ${schemaCode(vars)};`,
    '',
    '$(() => {',
    '  registerMvuSchema(Schema);',
    '});',
    '',
  ].join('\n');
}

/**
 * The same zod schema, built inside the tool, so the simulator checks values exactly the way the card will.
 * Runs code generated by schemaCode() only (names and texts are escaped there), never code from imported cards.
 */
export function buildSchema(vars: VarNode[]): z.ZodType {
  return new Function('z', `return ${schemaCode(vars)};`)(z);
}

/** The script that loads MVU itself. */
export const mvuScript = () => `import '${MVU_BUNDLE_URL}';\n`;
